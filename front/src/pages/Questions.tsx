export const Questions: React.FC = () => {
    const [activeIndex, setActiveIndex] = useState<number | null>(null);

    const toggleAccordion = (index: number): void => {
        setActiveIndex((prevIndex) => (prevIndex === index ? null : index));
    };

    return (
        <section className="w-full mx-auto px-4 md:px-25 py-10 overflow-hidden" dir="rtl">
            {/* أنيميشن دخول العنوان */}
            <motion.div
                initial={{ opacity: 0, y: -20 }}
                whileInView={{ opacity: 1, y: 0 }}
                viewport={{ once: true }}
                transition={{ duration: 0.6 }}
                className="text-center mb-8"
            >
                <h2 className="text-2xl md:text-5xl font-bold text-brand-red leading-relaxed">
                    لماذا سأسجل أبنائي في أكاديمية اللغة اليابانية ؟
                </h2>
            </motion.div>

            {/* أنيميشن دخول الصورة */}
            <motion.div
                initial={{ opacity: 0, scale: 0.95 }}
                whileInView={{ opacity: 1, scale: 1 }}
                viewport={{ once: true }}
                transition={{ duration: 0.6, delay: 0.2 }}
                className="w-full mx-auto mb-10"
            >
                <img
                    className="w-full h-auto rounded-2xl shadow-md object-cover"
                    src={question_img}
                    alt="أسئلة وأجوبة أكاديمية اللغة اليابانية"
                />
            </motion.div>

            {/* قائمة الأسئلة (Accordion) مع أنيميشن متسلسل (Stagger) */}
            <motion.div
                className="space-y-4 my-8"
                initial="hidden"
                whileInView="visible"
                viewport={{ once: true, margin: "-100px" }}
                variants={{
                    hidden: { opacity: 0 },
                    visible: {
                        opacity: 1,
                        transition: {
                            staggerChildren: 0.1 // يظهر كل سؤال بعد الآخر بـ 0.1 ثانية
                        }
                    }
                }}
            >
                {accordionData.map((item, index) => {
                    const isOpen = activeIndex === index;
                    return (
                        <motion.div
                            key={index}
                            variants={{
                                hidden: { opacity: 0, y: 20 },
                                visible: { opacity: 1, y: 0, transition: { duration: 0.5 } }
                            }}
                            className={`border rounded-xl overflow-hidden transition-colors duration-300 shadow-sm ${isOpen ? "border-brand-gold bg-white" : "border-gray-200 bg-white"
                                }`}
                        >
                            {/* زر السؤال */}
                            <button
                                type="button"
                                onClick={() => toggleAccordion(index)}
                                aria-expanded={isOpen}
                                aria-controls={`accordion-content-${index}`}
                                id={`accordion-header-${index}`}
                                className={`w-full flex items-center justify-between p-4 md:p-5 text-right transition-colors duration-200 focus:outline-none ${isOpen
                                    ? "bg-brand-red text-white"
                                    : "bg-gray-50 hover:bg-brand-gold/10 text-brand-black"
                                    }`}
                            >
                                <span className="text-2xl md:text-3xl font-semibold leading-relaxed">
                                    {item.title}
                                </span>
                                <GoChevronDown
                                    className={`w-6 h-6 shrink-0 transition-transform duration-300 ${isOpen ? "rotate-180 text-brand-gold" : "text-brand-black"
                                        }`}
                                />
                            </button>

                            {/* محتوى الإجابة باستخدام AnimatePresence */}
                            <AnimatePresence initial={false}>
                                {isOpen && (
                                    <motion.div
                                        id={`accordion-content-${index}`}
                                        role="region"
                                        aria-labelledby={`accordion-header-${index}`}
                                        initial={{ height: 0, opacity: 0 }}
                                        animate={{ height: "auto", opacity: 1 }}
                                        exit={{ height: 0, opacity: 0 }}
                                        transition={{ duration: 0.3, ease: "easeInOut" }}
                                        className="overflow-hidden"
                                    >
                                        {/* وضعنا البادينج هنا لضمان دقة حساب الطول (Height) أثناء الأنيميشن */}
                                        <div className="p-5 border-t border-brand-gold/20">
                                            <p className="text-brand-black text-xl md:text-2xl leading-relaxed">
                                                {item.content}
                                            </p>
                                        </div>
                                    </motion.div>
                                )}
                            </AnimatePresence>
                        </motion.div>
                    );
                })}
            </motion.div>
        </section>
    );
};

export default Questions;